// Bake Spotify track metadata (title, artist, cover, 30s preview mp3) into
// src/config/spotify-meta.generated.ts for the static MusicPlayer popup.
//
// Usage:  npm run songs:sync
// It reads every spotify.com/track/... URL from src/config/site.ts.

import fs from "node:fs";
import path from "node:path";
import spotifyUrlInfo from "spotify-url-info";

const { getPreview } = spotifyUrlInfo(fetch);

const sitePath = path.resolve("src/config/site.ts");
const site = fs.readFileSync(sitePath, "utf8");

// Collect track URLs (including intl-XX variants), normalized.
const urls = [
  ...new Set(
    [...site.matchAll(/https:\/\/open\.spotify\.com\/(?:intl-[a-z]{2}\/)?track\/[A-Za-z0-9]+/g)].map(
      (m) => m[0].replace(/\/intl-[a-z]{2}\//, "/"),
    ),
  ),
];

if (urls.length === 0) {
  console.log("No Spotify track URLs found in src/config/site.ts");
  process.exit(0);
}

const results = [];

for (const url of urls) {
  try {
    const data = await getPreview(url);
    const audio = data.audio ?? "";
    if (!data.title || !data.image) {
      console.warn(`! skipped (missing fields): ${url}`);
      continue;
    }
    results.push({
      spotify: url,
      title: data.title,
      artist: data.artist,
      image: data.image,
      audio,
    });
    console.log(
      `+ ${data.title} — ${data.artist}${audio ? " (preview ok)" : " (no preview)"}`,
    );
  } catch {
    console.warn(`! failed: ${url}`);
    results.push({
      spotify: url,
      title: "",
      artist: "",
      image: "",
      audio: "",
    });
  }
}

const file = `// AUTO-GENERATED by \`npm run songs:sync\` — do not edit by hand.
// Refreshes 30s Spotify preview URLs; re-run if playback stops working.

export type SpotifyMeta = {
  spotify: string;
  title: string;
  artist: string;
  image: string;
  audio: string;
};

export const spotifyMeta: SpotifyMeta[] = ${JSON.stringify(results, null, 2)};
`;

fs.writeFileSync(
  path.resolve("src/config/spotify-meta.generated.ts"),
  file,
);

console.log(`\nWrote src/config/spotify-meta.generated.ts (${results.length} tracks)`);
